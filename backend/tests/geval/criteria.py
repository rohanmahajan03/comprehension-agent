"""Frozen G-Eval criteria + evaluation steps, one per question in
tests/geval_test_suite.md.

`criteria` is copied verbatim from the markdown. `evaluation_steps` is
derived from that criteria text by hand and hardcoded here rather than
generated by GEval at runtime (which would call an LLM on every test run and
make the rubric non-deterministic across runs). If a question's criterion in
the markdown changes, regenerate its steps and update them here — don't let
GEval regenerate them implicitly by omitting evaluation_steps.
"""

from typing import NamedTuple


class GEvalSpec(NamedTuple):
    criteria: str
    evaluation_steps: list[str]


